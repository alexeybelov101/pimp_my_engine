#pragma once
#include <cmath>

namespace GasDynamics {
    // =========================================================================
    // Базовые физические константы (Согласованный набор для выхлопных газов)
    // =========================================================================

    constexpr double GAMMA = 1.35;            // Показатель адиабаты (горячий выхлоп)
    constexpr double R_SPECIFIC = 287.0;      // Газовая постоянная воздуха/газов [Дж/(кг*К)]

    // Производные термодинамические величины (строго согласованы с GAMMA и R)
    constexpr double CV = R_SPECIFIC / (GAMMA - 1.0);       // Теплоемкость при пост. объеме
    constexpr double CP = GAMMA * CV;                       // Теплоемкость при пост. давлении

    // =========================================================================
    // Пределы устойчивости и граничные условия
    // =========================================================================

    constexpr double T_EXHAUST_MAX = 1200.0;  // К (Ожидаемый пик температуры)
    constexpr double MACH_MAX = 2.0;          // Максимальное ожидаемое число Маха

    // Скорость звука при максимальной температуре: c = sqrt(gamma * R * T)
    constexpr double C_MAX = std::sqrt(GAMMA * R_SPECIFIC * T_EXHAUST_MAX);

    // Максимальная скорость потока
    constexpr double U_MAX = MACH_MAX * C_MAX;

    // Максимальная скорость распространения информации (для расчета шага по времени)
    constexpr double WAVE_SPEED_MAX = U_MAX + C_MAX;

    // Коэффициент Куранта-Фридрихса-Леви
    // ВНИМАНИЕ: Для явных схем (HLLC/Roe) строго рекомендуется CFL <= 0.9
    // Значение > 1.0 приведет к неустойчивости и NaN
    constexpr double CFL = 0.8;

    // =========================================================================
    // Атмосферные и начальные условия
    // =========================================================================

    constexpr double P_ATM = 101325.0;        // Па (Атмосферное давление)
    constexpr double T_AMBIENT = 293.0;       // К (20°C)
    constexpr double RHO_AMBIENT = P_ATM / (R_SPECIFIC * T_AMBIENT); // ~1.204 кг/м³

}
